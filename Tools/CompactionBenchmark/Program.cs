using System.Diagnostics;
using System.IO;
using System.Text.Json;
using Lertaro.Core;
using Lertaro.Core.IndexV2;
using Lertaro.Core.IndexV2.Persistence;
using Lertaro.Core.IndexV2.Search;

var rows = args.Length > 0 ? int.Parse(args[0]) : 500_000;
var rounds = args.Length > 1 ? int.Parse(args[1]) : 10;
if (rows < 100 || rounds < 1)
    throw new ArgumentException("Use at least 100 rows and one round.");
var directory = Directory.CreateTempSubdirectory("lertaro-compaction-bench-").FullName;
try
{
    var path = Path.Combine(directory, "index.bin");
    using (var store = new FileRecordStore { SourceKey = "C", RootId = 1 })
    {
        store.Records.Capacity = rows;
        store.Records.Add(new FileRecord(1, 1, "", FileRecordFlags.Directory | FileRecordFlags.SourceRoot));
        for (var id = 2; id <= rows; id++)
            store.Records.Add(new FileRecord((UInt128)id, 1, $"document_{id:D8}.txt", FileRecordFlags.None, id));
        SnapshotWriter.Write(store, path);
    }
    using var index = new LiveIndex(Snapshot.Open(path));
    void Search(Action<SearchResult> receive) => IndexV2Searcher.SearchStreaming(index, "document_00000042",
        20, receive, CancellationToken.None);
    for (var i = 0; i < 10; i++)
        Search(_ => { });
    index.Compact(path, force: true);

    var searchTimes = new List<double>();
    var firstResultTimes = new List<double>();
    var compactTimes = new List<double>();
    using var searching = new AutoResetEvent(false);
    using var completed = new AutoResetEvent(false);
    using var ready = new ManualResetEventSlim();
    using var stop = new CancellationTokenSource();
    Exception? searchError = null;
    var searcher = new Thread(() =>
    {
        try
        {
            ready.Set();
            while (!stop.IsCancellationRequested)
            {
                searching.WaitOne();
                if (stop.IsCancellationRequested) break;
                // Issue a query after the main thread has started the real compaction.
                Thread.Sleep(5);
                var clock = Stopwatch.StartNew();
                var first = -1.0;
                Search(_ => { if (first < 0) first = clock.Elapsed.TotalMilliseconds; });
                searchTimes.Add(clock.Elapsed.TotalMilliseconds);
                if (first < 0)
                    throw new InvalidOperationException("A known result disappeared during compaction.");
                firstResultTimes.Add(first);
                completed.Set();
            }
        }
        catch (Exception ex) { searchError = ex; completed.Set(); }
    });
    searcher.Start();
    ready.Wait();
    var allocatedBefore = GC.GetTotalAllocatedBytes(precise: true);
    try
    {
        for (var round = 0; round < rounds; round++)
        {
            index.Mutate((_, delta) => delta.Upsert((UInt128)(rows + round + 1), 1,
                $"new_{round}.txt", FileRecordFlags.None, 0, 0, 0, 0));
            searching.Set();
            var clock = Stopwatch.StartNew();
            index.Compact(path);
            compactTimes.Add(clock.Elapsed.TotalMilliseconds);
            if (!completed.WaitOne(TimeSpan.FromSeconds(30)))
                throw new TimeoutException("Concurrent search did not finish.");
            if (searchError != null) break;
        }
    }
    finally
    {
        stop.Cancel();
        searching.Set();
        searcher.Join();
    }
    if (searchError != null) throw new InvalidOperationException("Concurrent search failed.", searchError);
    using var final = Snapshot.Open(path);
    if (final.Count != rows + rounds) throw new InvalidOperationException("Compaction lost rows.");
    Console.WriteLine(JsonSerializer.Serialize(new
    {
        rows, rounds, samples = searchTimes.Count,
        search_ms = Summarize(searchTimes), first_result_ms = Summarize(firstResultTimes),
        compaction_ms = Summarize(compactTimes),
        process_allocated_bytes = GC.GetTotalAllocatedBytes(true) - allocatedBefore,
        peak_working_set_bytes = Process.GetCurrentProcess().PeakWorkingSet64,
        final_rows = final.Count,
    }, new JsonSerializerOptions { WriteIndented = true }));
}
finally
{
    // This run owns exactly this directory, generated by CreateTempSubdirectory.
    Directory.Delete(directory, recursive: true);
}

static object Summarize(List<double> times)
{
    times.Sort();
    double Percentile(double p) => times.Count == 0 ? 0 : times[Math.Clamp((int)Math.Ceiling(times.Count * p) - 1, 0, times.Count - 1)];
    return new { p50 = Percentile(.5), p95 = Percentile(.95), p99 = Percentile(.99), max = Percentile(1) };
}
